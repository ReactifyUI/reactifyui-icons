import fs from "fs"
import path from "path"

const ICONS_DIR = path.resolve("src/react/icons")
const INDEX_FILE = path.join(ICONS_DIR, "index.ts")

function isIconFile(file) {
    return (
        file.endsWith(".tsx") &&
        !file.endsWith(".test.tsx") &&
        file !== "index.ts"
    )
}

function generateIndex() {
    if (!fs.existsSync(ICONS_DIR)) {
        console.error("❌ Icons directory not found:", ICONS_DIR)
        process.exit(1)
    }

    const files = fs
        .readdirSync(ICONS_DIR)
        .filter(isIconFile)
        .sort((a, b) => a.localeCompare(b))

    if (files.length === 0) {
        console.warn("⚠️ No icon components found")
    }

    const content =
        `// AUTO-GENERATED FILE — DO NOT EDIT\n` +
        `// Generated by scripts/generate-icons-index.js\n\n` +
        files
            .map((file) => {
                const name = path.basename(file, ".tsx")
                return `export { default as ${name} } from "./${name}"`
            })
            .join("\n") +
        "\n"

    fs.writeFileSync(INDEX_FILE, content, "utf8")

    console.log(`✅ icons/index.ts generated (${files.length} icons)`)
}

generateIndex()
