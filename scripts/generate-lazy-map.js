import fs from "fs"
import path from "path"

const ICONS_DIR = path.resolve("src/react/icons")
const MAP_FILE = path.resolve("src/react/dynamicMap.ts")

function isIconFile(file) {
    return (
        file.endsWith(".tsx") &&
        !file.endsWith(".test.tsx") &&
        file !== "index.ts"
    )
}

function generateLazyMap() {
    if (!fs.existsSync(ICONS_DIR)) {
        console.error("❌ Icons directory not found:", ICONS_DIR)
        process.exit(1)
    }

    const files = fs
        .readdirSync(ICONS_DIR)
        .filter(isIconFile)
        .sort((a, b) => a.localeCompare(b))

    if (files.length === 0) {
        console.warn("⚠️ No icon components found to generate map")
    }

    const imports = `import { lazy } from "react"\n\n`
    
    const entries = files
        .map((file) => {
            const name = path.basename(file, ".tsx")
            return `  ${name}: lazy(() => import("./icons/${name}"))`
        })
        .join(",\n")

    const content =
        `// AUTO-GENERATED FILE — DO NOT EDIT\n` +
        `// Generated by scripts/generate-lazy-map.js\n\n` +
        imports +
        `export const dynamicMap: Record<string, React.LazyExoticComponent<any>> = {\n` +
        entries +
        `\n};\n`

    fs.writeFileSync(MAP_FILE, content, "utf8")

    console.log(`✅ react/dynamicMap.ts generated (${files.length} mappings)`)
}

generateLazyMap()
